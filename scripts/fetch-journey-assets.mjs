import fs from "node:fs/promises";
const current = [
  1, 2, 4, 5, 7, 8, 10, 11, 12, 16, 17, 25, 26, 41, 42, 54, 55, 74, 75, 95, 130,
  133,
];
const additions = [
  403, 404, 405, 522, 523, 587, 650, 651, 656, 657, 661, 662, 722, 723, 725,
  726, 728, 729, 744, 745,
];
const stats = {};
const extra = [];
const habitats = {
  403: "cave",
  404: "cave",
  405: "cave",
  522: "unova",
  523: "unova",
  587: "unova",
  650: "kalos",
  651: "kalos",
  656: "kalos",
  657: "kalos",
  661: "kalos",
  662: "kalos",
  722: "alola",
  723: "alola",
  725: "alola",
  726: "alola",
  728: "alola",
  729: "alola",
  744: "alola",
  745: "alola",
};
async function json(url) {
  const r = await fetch(url);
  if (!r.ok) throw Error(`${r.status} ${url}`);
  return r.json();
}
for (const id of [...current, ...additions]) {
  const [pokemon, species] = await Promise.all([
    json(`https://pokeapi.co/api/v2/pokemon/${id}`),
    json(`https://pokeapi.co/api/v2/pokemon-species/${id}`),
  ]);
  const s = Object.fromEntries(
    pokemon.stats.map((s) => [s.stat.name, s.base_stat]),
  );
  stats[id] = {
    legalMoves: pokemon.moves.map((m) => m.move.name),
    hp: s.hp,
    attack: s.attack,
    defense: s.defense,
    spAttack: s["special-attack"],
    spDefense: s["special-defense"],
    speed: s.speed,
    catchRate: species.capture_rate,
    types: pokemon.types.map((t) => t.type.name),
  };
  if (additions.includes(id)) {
    const name =
      species.names.find((n) => n.language.name.toLowerCase() === "zh-hans")
        ?.name || pokemon.name;
    const type = pokemon.types[0].type.name;
    extra.push({
      id,
      name,
      type,
      baseHp: s.hp,
      attack: Math.round(s.attack / 6),
      moves: [],
      habitat: [habitats[id]],
      description: `来自${habitats[id] === "unova" ? "合众" : habitats[id] === "kalos" ? "卡洛斯" : habitats[id] === "alola" ? "阿罗拉" : "神奥"}的伙伴，一起发现新的道路。`,
    });
    for (const back of [false, true]) {
      try {
        await fs.access(`public/game/pokemon/${id}${back ? "-back" : ""}.png`);
        continue;
      } catch {}
      const url = `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/${back ? "back/" : ""}${id}.png`;
      const response = await fetch(url);
      if (!response.ok) throw Error(`Missing sprite ${id}`);
      const bytes = new Uint8Array(await response.arrayBuffer());
      if (bytes[0] !== 137 || bytes[1] !== 80) throw Error("Invalid PNG");
      await fs.writeFile(
        `public/game/pokemon/${id}${back ? "-back" : ""}.png`,
        bytes,
      );
    }
  }
  process.stdout.write(`${id} `);
}
await fs.writeFile(
  "src/adventure/species-stats.ts",
  `// Source: PokeAPI pokemon and pokemon-species endpoints; generated by scripts/fetch-journey-assets.mjs.\nexport const SPECIES_STATS: Record<number,{hp:number;attack:number;defense:number;spAttack:number;spDefense:number;speed:number;catchRate:number;types:string[];legalMoves:string[]}> = ${JSON.stringify(stats, null, 2)}\n`,
);
await fs.writeFile(
  "src/adventure/additional-species.ts",
  `// Source: PokeAPI; names and habitat assignment for this adventure.\nexport const ADDITIONAL_SPECIES = ${JSON.stringify(extra, null, 2)}\n`,
);
